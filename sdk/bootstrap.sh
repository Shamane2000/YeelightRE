#!/usr/bin/env bash
# bootstrap.sh -- reproducible setup of the mcufw build environment.
#
#   1. clone/checkout the pinned EZ-Connect-Lite (WMSDK) tree into vendor/
#   2. verify the vendor axf2firmware host tool is present and executable
#   3. verify the ARM toolchain version against sdk.lock
#   4. write vendor/SDK_PROVENANCE.txt (commit + tool hashes + versions)
#
# Idempotent: re-running only re-verifies.
set -euo pipefail

here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
cd "$here"

# shellcheck source=sdk.lock
. ./sdk.lock

SDK_DIR="vendor/ez-connect-lite"
AXF2FW="$SDK_DIR/sdk/tools/bin/Linux/axf2firmware"

log() { printf '[bootstrap] %s\n' "$*"; }
die() { printf '[bootstrap] FEHLER: %s\n' "$*" >&2; exit 1; }

# --- 1. vendor tree -------------------------------------------------------
if [ ! -d "$SDK_DIR/.git" ]; then
	log "klone $ECL_URL -> $SDK_DIR"
	mkdir -p vendor
	git clone --quiet "$ECL_URL" "$SDK_DIR"
else
	log "vendor tree vorhanden, pruefe Commit"
fi

if ! git -C "$SDK_DIR" cat-file -e "${ECL_COMMIT}^{commit}" 2>/dev/null; then
	log "gepinnter Commit fehlt lokal, hole nach"
	git -C "$SDK_DIR" fetch --quiet --tags origin || die "git fetch fehlgeschlagen"
fi
git -C "$SDK_DIR" -c advice.detachedHead=false checkout --quiet "$ECL_COMMIT"

got=$(git -C "$SDK_DIR" rev-parse HEAD)
[ "$got" = "$ECL_COMMIT" ] || die "Commit-Mismatch: $got != $ECL_COMMIT"
log "SDK-Commit OK: $got"

# --- 2. axf2firmware ------------------------------------------------------
[ -f "$AXF2FW" ] || die "$AXF2FW fehlt (sdk/tools/bin/Linux/axf2firmware)"
chmod +x "$AXF2FW"
# smoke test: the tool needs two args, prints usage and returns 1 without them
usage=$("$AXF2FW" 2>&1 || true)
if ! printf '%s' "$usage" | grep -qi 'usage'; then
	die "axf2firmware laeuft nicht (i386-Host-Tool, benoetigt ld-linux.so.2): $usage"
fi
log "axf2firmware OK (axf2firmware <in.axf|in.elf> <out.bin>)"

# --- 3. toolchain ---------------------------------------------------------
command -v arm-none-eabi-gcc >/dev/null || die "arm-none-eabi-gcc nicht im PATH"
gccver=$(arm-none-eabi-gcc -dumpversion)
log "arm-none-eabi-gcc $gccver (Minimum $MIN_GCC_VERSION)"
arm-none-eabi-gcc --version | head -1

# --- 4. provenance --------------------------------------------------------
{
	echo "# generated by sdk/bootstrap.sh -- do not edit"
	echo "ecl_url=$ECL_URL"
	echo "ecl_commit=$ECL_COMMIT"
	echo "ecl_commit_date=$(git -C "$SDK_DIR" show -s --format=%cI HEAD)"
	echo "axf2firmware_sha256=$(sha256sum "$AXF2FW" | cut -d' ' -f1)"
	echo "arm_none_eabi_gcc=$gccver"
	echo "host=$(uname -srm)"
} > vendor/SDK_PROVENANCE.txt

log "Provenance geschrieben: vendor/SDK_PROVENANCE.txt"
cat vendor/SDK_PROVENANCE.txt
